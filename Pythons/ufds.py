def drawUF(a):
    dot = gv.Digraph(comment='UFDS Chimbote 1500 Nodos')
    n = len(a)
    for i in range(n):
        dot.node(str(i), str(i))
    for i in range(n):
        if a[i] >= 0:
            dot.edge(str(i), str(a[i]))
    dot.graph_attr['rankdir'] = 'BT'
    return dot

def find(s, a):
    i = a
    while s[i] >= 0:
        i = s[i]
    return i

def union(s, a, b):
    pa = find(s, a)
    pb = find(s, b)
    if pa == pb:
        return
    if s[pa] < s[pb]:
        s[pa] += s[pb]
        s[pb] = pa
    elif s[pb] < s[pa]:
        s[pb] += s[pa]
        s[pa] = pb
    else:
        s[pa] += s[pb]
        s[pb] = pa

def verificar_conexion(s, a, b):
    return find(s, a) == find(s, b)

