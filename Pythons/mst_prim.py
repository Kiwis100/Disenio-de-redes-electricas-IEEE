def mapear_mst_chimbote(nodos, parent):
    g = gv.Graph("Mapa_MST_Chimbote")
    g.graph_attr["layout"] = "neato"
    g.graph_attr["splines"] = "false"
    g.node_attr["shape"] = "point"
    g.node_attr["width"] = "0.03"
    g.node_attr["color"] = "#1f77b4"
    g.edge_attr["color"] = "#ff7f0e"
    g.edge_attr["penwidth"] = "0.7"

    # Escalar coordenadas UTM (X, Y) a pulgadas para que graphviz respete el mapa
    min_x = min(n["X"] for n in nodos)
    max_x = max(n["X"] for n in nodos)
    min_y = min(n["Y"] for n in nodos)
    max_y = max(n["Y"] for n in nodos)
    escala = 14.0 / max(max_x - min_x, max_y - min_y)

    for n in nodos:
        px = (n["X"] - min_x) * escala
        py = (n["Y"] - min_y) * escala
        g.node(str(n["idx"]), pos=f"{px:.4f},{py:.4f}!")

    # Dibujar las 1,499 líneas óptimas elegidas por Prim
    for i in range(1, len(nodos)):
        if parent[i] != -1:
            g.edge(str(parent[i]), str(i))

    return g


